
CREATE TABLE usuario (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         email VARCHAR(150) NOT NULL UNIQUE,
                         senha_hash VARCHAR(100) NOT NULL,
                         perfil VARCHAR(20) NOT NULL DEFAULT 'CLIENTE'
                             CHECK (perfil IN ('ADMIN', 'OPERADOR', 'CLIENTE')),
                         ativo BOOLEAN NOT NULL DEFAULT TRUE,
                         criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE cliente (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         usuario_id BIGINT NOT NULL UNIQUE,
                         nome VARCHAR(150) NOT NULL,
                         cpf VARCHAR(11) UNIQUE,
                         telefone VARCHAR(20),
                         rua VARCHAR(150),
                         numero VARCHAR(20),
                         cidade VARCHAR(100),
                         uf CHAR(2),
                         cep VARCHAR(8),
                         criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT fk_cliente_usuario
                             FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE categoria (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           nome VARCHAR(100) NOT NULL UNIQUE,
                           descricao VARCHAR(255)
);

CREATE TABLE fornecedor (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            nome VARCHAR(150) NOT NULL,
                            cnpj VARCHAR(14) UNIQUE,
                            email VARCHAR(150),
                            telefone VARCHAR(20),
                            ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE produto (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         sku VARCHAR(50) NOT NULL UNIQUE,
                         nome VARCHAR(150) NOT NULL,
                         descricao TEXT,
                         preco NUMERIC(10, 2) NOT NULL CHECK (preco >= 0),
                         quantidade_estoque INTEGER NOT NULL DEFAULT 0
                             CHECK (quantidade_estoque >= 0),
                         estoque_minimo INTEGER NOT NULL DEFAULT 0
                             CHECK (estoque_minimo >= 0),
                         categoria_id BIGINT,
                         fornecedor_id BIGINT,
                         ativo BOOLEAN NOT NULL DEFAULT TRUE,
                         version BIGINT NOT NULL DEFAULT 0,
                         criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                         atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT fk_produto_categoria
                             FOREIGN KEY (categoria_id) REFERENCES categoria(id),

                         CONSTRAINT fk_produto_fornecedor
                             FOREIGN KEY (fornecedor_id) REFERENCES fornecedor(id)
);

CREATE TABLE pedido (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        cliente_id BIGINT NOT NULL,
                        status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
                            CHECK (
                                status IN (
                                           'PENDENTE',
                                           'PAGO',
                                           'ENVIADO',
                                           'ENTREGUE',
                                           'CANCELADO'
                                    )
                                ),
                        valor_total NUMERIC(12, 2) NOT NULL DEFAULT 0
                            CHECK (valor_total >= 0),
                        criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                        CONSTRAINT fk_pedido_cliente
                            FOREIGN KEY (cliente_id) REFERENCES cliente(id)
);

CREATE TABLE item_pedido (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             pedido_id BIGINT NOT NULL,
                             produto_id BIGINT NOT NULL,
                             quantidade INTEGER NOT NULL CHECK (quantidade > 0),
                             preco_unitario NUMERIC(10, 2) NOT NULL
                                 CHECK (preco_unitario >= 0),

                             CONSTRAINT fk_item_pedido_pedido
                                 FOREIGN KEY (pedido_id) REFERENCES pedido(id),

                             CONSTRAINT fk_item_pedido_produto
                                 FOREIGN KEY (produto_id) REFERENCES produto(id),

                             CONSTRAINT uk_item_pedido_produto
                                 UNIQUE (pedido_id, produto_id)
);

CREATE TABLE movimentacao_estoque (
                                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      produto_id BIGINT NOT NULL,
                                      tipo VARCHAR(10) NOT NULL
                                          CHECK (tipo IN ('ENTRADA', 'SAIDA')),
                                      quantidade INTEGER NOT NULL CHECK (quantidade > 0),
                                      motivo VARCHAR(30) NOT NULL
                                          CHECK (
                                              motivo IN (
                                                         'COMPRA_FORNECEDOR',
                                                         'VENDA',
                                                         'AJUSTE',
                                                         'CANCELAMENTO',
                                                         'PERDA'
                                                  )
                                              ),
                                      pedido_id BIGINT,
                                      usuario_id BIGINT,
                                      observacao VARCHAR(255),
                                      criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                      CONSTRAINT fk_movimentacao_produto
                                          FOREIGN KEY (produto_id) REFERENCES produto(id),

                                      CONSTRAINT fk_movimentacao_pedido
                                          FOREIGN KEY (pedido_id) REFERENCES pedido(id),

                                      CONSTRAINT fk_movimentacao_usuario
                                          FOREIGN KEY (usuario_id) REFERENCES usuario(id)
);

CREATE TABLE historico_status_pedido (
                                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         pedido_id BIGINT NOT NULL,
                                         status_anterior VARCHAR(20),
                                         status_novo VARCHAR(20) NOT NULL,
                                         alterado_por BIGINT,
                                         alterado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                         CONSTRAINT fk_historico_pedido
                                             FOREIGN KEY (pedido_id) REFERENCES pedido(id),

                                         CONSTRAINT fk_historico_usuario
                                             FOREIGN KEY (alterado_por) REFERENCES usuario(id),

                                         CONSTRAINT ck_historico_status_anterior
                                             CHECK (
                                                 status_anterior IS NULL OR status_anterior IN (
                                                                                                'PENDENTE', 'PAGO', 'ENVIADO', 'ENTREGUE', 'CANCELADO'
                                                     )
                                                 ),

                                         CONSTRAINT ck_historico_status_novo
                                             CHECK (
                                                 status_novo IN (
                                                                 'PENDENTE', 'PAGO', 'ENVIADO', 'ENTREGUE', 'CANCELADO'
                                                     )
                                                 )
);

CREATE INDEX idx_produto_nome ON produto(nome);
CREATE INDEX idx_produto_categoria ON produto(categoria_id);
CREATE INDEX idx_produto_fornecedor ON produto(fornecedor_id);
CREATE INDEX idx_pedido_cliente ON pedido(cliente_id);
CREATE INDEX idx_pedido_status ON pedido(status);
CREATE INDEX idx_item_pedido_pedido ON item_pedido(pedido_id);
CREATE INDEX idx_movimentacao_produto_data
    ON movimentacao_estoque(produto_id, criado_em);
CREATE INDEX idx_movimentacao_pedido
    ON movimentacao_estoque(pedido_id);
CREATE INDEX idx_historico_pedido_data
    ON historico_status_pedido(pedido_id, alterado_em);
